import 'dart:async' show unawaited;

/// 겹치는 비동기 요청을 "최신 것만" 실행하게 조율한다.
///
/// **어디서 왜 필요한가** — 바람지도 시간 슬라이더는 `divisions` 없는 연속
/// `Slider`라 드래그 한 번에 `onChanged`가 초당 수십 번, 서로 다른 시각으로
/// 불린다. 시각이 바뀔 때마다 히트맵을 다시 굽는데, 굽는 작업 자체가 무거워
/// (`compute()` 아이솔레이트 스폰 + `WindField` 격자 직렬화 + 픽셀 채우기,
/// 배경만 굽는 경우도 실측 300ms대) 매 호출마다 새로 시작하면 한 번의 드래그
/// 동안 수십 개의 아이솔레이트가 동시에 뜬다. 그 스폰·직렬화 자체와 CPU 경합이
/// UI 스레드의 프레임 렌더링을 밀어내 슬라이더가 버벅였다(2026-08-08 사용자
/// 제보 — "지도에서 날짜를 이동할 때 반응 속도가 너무 느리다").
///
/// [run]은 이미 하나가 실행 중이면 새로 시작하지 않고 "그새 더 최신 요청이
/// 왔다"는 표시만 남긴다. 실행 중이던 것이 끝나면 표시가 남아 있을 때만
/// [task]를 한 번 더 실행한다 — 그 시점엔 [task]가 어차피 "지금" 상태(예:
/// 위젯의 최신 `field`)를 다시 읽으므로 코디네이터가 값을 따로 들고 다닐
/// 필요가 없다. 그래서 실제로 무거운 작업은 한 번의 빠른 드래그당 몇 번만
/// 돌고(첫 시작 + 끝날 때마다 그사이 쌓인 요청을 한 번씩 흡수), 중간에
/// 지나친 시각들은 건너뛴다 — 실행이 끝났을 때는 항상 그 순간까지의
/// **마지막 상태**를 반영한 결과로 수렴한다.
///
/// **한 코디네이터엔 항상 같은 [task]를 넘긴다.** 실행 중일 때 걸어 둔
/// "표시"는 다음에 어떤 [task]를 돌릴지 기억하지 않고, 이어서 도는 것은
/// 항상 **맨 처음 넘긴** [task]다. 그 [task]가 매번 최신 상태를 다시 읽는
/// 클로저(예: `() => _doRebuildHeatmap()`처럼 위젯의 현재 `field`를 그때그때
/// 읽는 함수)라야 이 클래스의 "최신 것만 반영" 보장이 성립한다.
class LatestOnlyRunner {
  bool _running = false;
  bool _dirty = false;

  /// 실행 중이 아니면 [task]를 바로 돈다. 실행 중이면 끝난 뒤 한 번 더
  /// 돌 것을 표시만 해 두고 즉시 반환한다(호출자가 결과를 기다릴 필요가
  /// 없는 "발사 후 잊는" 갱신 트리거라 [run] 자체는 값을 반환하지 않는다).
  void run(Future<void> Function() task) {
    if (_running) {
      _dirty = true;
      return;
    }
    _running = true;
    unawaited(_drain(task));
  }

  Future<void> _drain(Future<void> Function() task) async {
    // 한 번 실행하고 나서 그사이 새 요청이 쌓였으면(_dirty) 한 번 더 —
    // 그 반복 중에도 또 쌓이면 dirty가 다시 서므로 계속 돈다. 어떤 요청이
    // 와도 결국 "요청이 더 이상 없을 때"까지 최소한의 횟수로 수렴한다.
    do {
      _dirty = false;
      await task();
    } while (_dirty);
    _running = false;
  }
}
